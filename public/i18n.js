  const LANGUAGES = Object.keys(MESSAGES);
  const FALLBACK = 'en';

  // The first supported language from a list such as navigator.languages or an
  // Accept-Language header ("de-CH,de;q=0.9,en;q=0.8").
  function pick(preferred) {
    const list = Array.isArray(preferred) ? preferred : String(preferred || '').split(',');
    for (const entry of list) {
      const base = String(entry).split(';')[0].trim().toLowerCase().split('-')[0];
      if (LANGUAGES.includes(base)) return base;
    }
    return FALLBACK;
  }

  function translator(lang) {
    const messages = MESSAGES[lang] || MESSAGES[FALLBACK];
    const t = (key, vars = {}) => {
      const text = messages[key] ?? MESSAGES[FALLBACK][key] ?? key;
      return text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
    };
    // Plurals: key.one for exactly one, key.other otherwise.
    t.n = (key, n, vars = {}) => t(`${key}.${n === 1 ? 'one' : 'other'}`, { ...vars, n });
    return t;
  }

  const api = { MESSAGES, LANGUAGES, pick, translator };
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.I18N = api;
